import { readFileSync, writeFileSync } from "node:fs";

/**
 * Generates app/src/icons.ts from @fluentui/svg-icons.
 *
 * Fluent System Icons (MIT), 24px regular: one grid for the whole app, so the
 * mix of 24/20/16/12 view boxes and 1.8/2/1.5 stroke widths stops existing.
 * The art is taken verbatim from the package — the previous set was drawn by
 * hand, which is why a "close" looked different in three places.
 */
const SRC = "node_modules/@fluentui/svg-icons/icons";
const OUT = "app/src/icons.ts";

/** Key used in the app -> Fluent icon file (24px regular). */
const NAMES = {
  back: "chevron_left",
  prev: "chevron_left",
  chevron: "chevron_right",
  twisty: "chevron_down",
  close: "dismiss",
  info: "info",
  settings: "settings",
  search: "search",
  home: "home",
  globe: "globe",
  library: "grid",
  trips: "arrow_routing",
  transit: "vehicle_subway",
  expand: "arrow_maximize",
  fit: "arrow_minimize",
  plus: "add",
  minus: "subtract",
  share: "share",
  download: "arrow_download",
  export: "document_pdf",
  calendar: "calendar",
  pin: "pin",
  generate: "sparkle",
  activity: "history",
  rename: "edit",
  remove: "delete",
  story: "chat",
  regenerate: "arrow_clockwise",
  qr: "qr_code",
  shield: "shield",
  check: "checkmark",
  external: "arrow_up_right",
  copy: "copy",
  location: "location",
  image: "image",
};

const entries = [];
for (const [key, fluent] of Object.entries(NAMES)) {
  const file = `${SRC}/${fluent}_24_regular.svg`;
  const svg = readFileSync(file, "utf8");
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>[\s\S]*$/, "").trim();
  if (!inner.startsWith("<")) throw new Error(`no path data in ${file}`);
  entries.push(`  ${JSON.stringify(key)}: ${JSON.stringify(inner)},`);
}

const body = `/**
 * The app's icon set: Fluent UI System Icons, 24px regular (MIT).
 *
 * Generated by scripts/build-icons.mjs — do not edit by hand, and do not draw a
 * glyph here. Two dozen hand-drawn icons had drifted into four view boxes and
 * three stroke widths; one grid is the point of this file.
 *
 * Paths are filled with \`currentColor\`, so colour comes from CSS like any text.
 */
export const ICON_PATHS = {
${entries.join("\n")}
} as const;

export type IconName = keyof typeof ICON_PATHS;

/**
 * One icon as markup, for the template strings the app builds itself.
 * \`size\` is the rendered box in CSS pixels; the geometry is always 24.
 */
export function icon(name: IconName, size = 16, className = ""): string {
  const cls = className ? \` class="\${className}"\` : "";
  // size 0 omits the attributes: the mobile chrome sizes its glyphs per class,
  // and a width/height here would override that CSS.
  const dims = size ? \` width="\${size}" height="\${size}"\` : "";
  return \`<svg viewBox="0 0 24 24"\${dims} fill="currentColor" aria-hidden="true"\${cls}>\${ICON_PATHS[name]}</svg>\`;
}
`;

writeFileSync(OUT, body, "utf8");
console.log(`wrote ${OUT} with ${entries.length} icons`);
